// Contact prompts
//
// Prompt only. We compose the message and hand it to the rep; we do not send
// it. A2P 10DLC registration and per-customer consent are prerequisites for
// outbound SMS, and a worklist that quietly texts on a rep's behalf is a TCPA
// exposure measured at $500–1,500 per message.

export function canText(item: FollowUpItem): boolean {
  return item.smsConsent && !item.doNotCall && Boolean(item.customerPhone)
}

export function canCall(item: FollowUpItem): boolean {
  return !item.doNotCall && Boolean(item.customerPhone)
}

/** Why a channel is unavailable, so a rep is never left guessing. */
export function contactBlockedReason(item: FollowUpItem): string | null {
  if (item.doNotCall) return 'Customer asked not to be contacted.'
  if (!item.customerPhone) return 'No phone number on file.'
  if (!item.smsConsent) return 'No SMS consent on file — call instead.'
  return null
}

function firstName(fullName: string): string {
  const first = fullName.trim().split(/\s+/)[0]
  return first && first.length > 1 ? first : fullName
}

/**
 * A text the rep can read, edit and send from their own device.
 *
 * Deliberately short and specific: it names the store, the vehicle and the one
 * reason for the message. Generic blasts are what customers opt out of.
 */
export function buildTextPrompt(item: FollowUpItem, storeName: string): string {
  const who = firstName(item.customerName)
  const vehicle = item.vehicleLabel ? ` on your ${item.vehicleLabel}` : ''

  switch (item.trigger) {
    case 'DECLINED_SERVICE_FOLLOW_UP':
      return `Hi ${who}, it's ${storeName}. Last visit we found work${vehicle} you decided to hold off on. It's still open and I can honour the same price — want me to look at a time this week?`
    case 'PPM_EXPIRING':
      return `Hi ${who}, ${storeName} here. You have prepaid service${vehicle} that expires soon — you've already paid for it. Can I get you booked before it lapses?`
    case 'WARRANTY_EXPIRING':
      return `Hi ${who}, it's ${storeName}. Your factory coverage${vehicle} is close to running out. Worth a quick chat about your options before it does — do you have a few minutes this week?`
    case 'OPEN_RECALL':
      return `Hi ${who}, ${storeName}. There's an open safety recall${vehicle}. The manufacturer covers it at no cost to you — can I book you in?`
    case 'DORMANT_CUSTOMER':
      return `Hi ${who}, it's ${storeName}. We haven't seen you${vehicle} in a while and wanted to check everything is running well. Anything you'd like us to look at?`
    case 'MISSED_APPOINTMENT':
      return `Hi ${who}, ${storeName} here. We missed you at your appointment${vehicle} — no problem at all. Want me to find another time?`
    case 'POST_VISIT_THANK_YOU':
    case 'CSI_PRE_EMPTION':
      return `Hi ${who}, it's ${storeName}. Just checking everything is right${vehicle} after your visit. If anything isn't, tell me and I'll sort it.`
    default:
      return `Hi ${who}, it's ${storeName} about your service${vehicle}. ${item.title}. Is now a good time for a quick call?`
  }
}
