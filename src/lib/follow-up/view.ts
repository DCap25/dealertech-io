export interface FollowUpFilters {
  owner?: FollowUpOwner | 'ALL'
  trigger?: string
  /** Only the four money-leaking types. */
  highValueOnly?: boolean
}

export function filterItems(items: FollowUpItem[], filters: FollowUpFilters): FollowUpItem[] {
  return items.filter((i) => {
    if (filters.owner && filters.owner !== 'ALL' && i.owner !== filters.owner) return false
    if (filters.trigger && i.trigger !== filters.trigger) return false
    if (filters.highValueOnly && !triggerMeta(i.trigger).highValue) return false
    return true
  })
}

export interface FollowUpSection {
  urgency: FollowUpUrgency
  label: string
  items: FollowUpItem[]
}

const SECTION_LABEL: Record<FollowUpUrgency, string> = {
  OVERDUE: 'Overdue',
  TODAY: 'Due today',
  UPCOMING: 'Coming up',
}

/**
 * Split into urgency bands, preserving the engine's ordering inside each.
 *
 * Empty bands are dropped rather than rendered as a heading over nothing — a
 * rep scanning for work should not have to read three headings to find out
 * there are two calls.
 */
export function groupByUrgency(items: FollowUpItem[], asOf: Date): FollowUpSection[] {
  const order: FollowUpUrgency[] = ['OVERDUE', 'TODAY', 'UPCOMING']
  return order
    .map((urgency) => ({
      urgency,
      label: SECTION_LABEL[urgency],
      items: items.filter((i) => classifyUrgency(i.dueAt, asOf) === urgency),
    }))
    .filter((section) => section.items.length > 0)
}

export interface FollowUpSummary {
  count: number
  value: number
  overdueCount: number
  highValueCount: number
  byOwner: { owner: FollowUpOwner; count: number }[]
  byTrigger: { trigger: string; label: string; count: number; value: number }[]
}

export function summarize(items: FollowUpItem[], asOf: Date): FollowUpSummary {
  const byOwnerCount = new Map<FollowUpOwner, number>()
  const byTrigger = new Map<string, { count: number; value: number }>()
  let value = 0
  let overdueCount = 0
  let highValueCount = 0

  for (const item of items) {
    value += item.estimatedValue
    if (classifyUrgency(item.dueAt, asOf) === 'OVERDUE') overdueCount += 1
    if (triggerMeta(item.trigger).highValue) highValueCount += 1

    byOwnerCount.set(item.owner, (byOwnerCount.get(item.owner) ?? 0) + 1)
    const t = byTrigger.get(item.trigger) ?? { count: 0, value: 0 }
    byTrigger.set(item.trigger, { count: t.count + 1, value: t.value + item.estimatedValue })
  }

  return {
    count: items.length,
    value,
    overdueCount,
    highValueCount,
    byOwner: [...byOwnerCount.entries()]
      .map(([owner, count]) => ({ owner, count }))
      .sort((a, b) => b.count - a.count),
    byTrigger: [...byTrigger.entries()]
      .map(([trigger, t]) => ({ trigger, label: triggerMeta(trigger).label, ...t }))
      .sort((a, b) => b.value - a.value || b.count - a.count),
  }
}

