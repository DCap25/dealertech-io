import type { CadenceTrigger } from '@/lib/cadence'
import type { WorklistItem } from '@/lib/cadence/worklist'

/**
 * Follow-up worklist presentation.
 *
 * Pure and I/O-free. The cadence engine decides what to chase and when; this
 * only decides how a rep reads it. Nothing here re-prioritises or re-schedules
 * a task — two different orders inside one product is how a worklist stops
 * being trusted.
 */

export type FollowUpOwner = 'ADVISOR' | 'BDC' | 'UNASSIGNED'
export type FollowUpUrgency = 'OVERDUE' | 'TODAY' | 'UPCOMING'

export interface FollowUpItem extends WorklistItem {
  /** From the rule that generated it. */
  owner: FollowUpOwner
  smsConsent: boolean
}

export function ownerFrom(role: string | null | undefined): FollowUpOwner {
  if (role === 'ADVISOR') return 'ADVISOR'
  if (role === 'BDC') return 'BDC'
  return 'UNASSIGNED'
}

/** Whole days past due. Negative means still ahead. */
export function overdueDays(dueAt: Date, asOf: Date): number {
  const startOfDue = new Date(dueAt).setHours(0, 0, 0, 0)
  const startOfNow = new Date(asOf).setHours(0, 0, 0, 0)
  return Math.round((startOfNow - startOfDue) / 86_400_000)
}

export function classifyUrgency(dueAt: Date, asOf: Date): FollowUpUrgency {
  const days = overdueDays(dueAt, asOf)
  if (days > 0) return 'OVERDUE'
  if (days === 0) return 'TODAY'
  return 'UPCOMING'
}

